// "golden retriever" -> { es: ['Perro', …], tipo: 'animal' } · null si no se conoce
export function claseEnEspanol(nombreIngles = '') {
  const nombre = nombreIngles.toLowerCase().split(',')[0].trim()
  if (CLASES_IMAGENET[nombre]) return CLASES_IMAGENET[nombre]
  return GRUPOS.find((g) => g.claves.some((c) => nombre.includes(c))) || null
}
